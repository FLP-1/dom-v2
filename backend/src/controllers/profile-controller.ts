// Importar módulos separados
export * from './profile/profile-crud';

// Importar funcionalidades adicionais
import { Request, Response } from 'express';
import { PrismaClient } from '@prisma/client';

const prisma = new PrismaClient();

/**
 * Buscar perfis por tipo
 */
export const getProfilesByType = async (req: Request, res: Response) => {
  try {
    const { profileType } = req.params;
    const { contextId, contextType, active } = req.query;

    const where: any = {
      profileType
    };

    if (contextId) where.contextId = contextId;
    if (contextType) where.contextType = contextType;
    if (active !== undefined) where.isActive = active === 'true';

    const profiles = await prisma.userProfile.findMany({
      where,
      include: {
        user: {
          select: {
            id: true,
            name: true,
            email: true
          }
        }
      },
      orderBy: { createdAt: 'desc' }
    });

    res.json({
      success: true,
      data: profiles
    });

  } catch (error) {
    console.error('Erro ao buscar perfis por tipo:', error);
    res.status(500).json({
      success: false,
      message: 'Erro interno do servidor'
    });
  }
};

/**
 * Obter estatísticas de perfis
 */
export const getProfileStats = async (req: Request, res: Response) => {
  try {
    const [totalProfiles, profilesByType, activeProfiles] = await Promise.all([
      // Total de perfis
      prisma.userProfile.count(),
      
      // Perfis por tipo
      prisma.userProfile.groupBy({
        by: ['profileType'],
        _count: {
          id: true
        }
      }),
      
      // Perfis ativos
      prisma.userProfile.count({
        where: { isActive: true }
      })
    ]);

    const stats = {
      total: totalProfiles,
      active: activeProfiles,
      inactive: totalProfiles - activeProfiles,
      byType: profilesByType
    };

    res.json({
      success: true,
      data: stats
    });

  } catch (error) {
    console.error('Erro ao obter estatísticas de perfis:', error);
    res.status(500).json({
      success: false,
      message: 'Erro interno do servidor'
    });
  }
};


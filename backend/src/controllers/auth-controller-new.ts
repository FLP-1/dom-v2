// Importar módulos separados
export * from './auth/auth-authentication';

// Importar funcionalidades de autorização
import { Request, Response, NextFunction } from 'express';
import jwt from 'jsonwebtoken';

const JWT_SECRET = process.env.JWT_SECRET || 'dom-v2-secret-key';

/**
 * Middleware de autenticação JWT
 */
export const authenticateToken = (req: Request, res: Response, next: NextFunction) => {
  const authHeader = req.headers['authorization'];
  const token = authHeader && authHeader.split(' ')[1];

  if (!token) {
    return res.status(401).json({
      success: false,
      message: 'Token de acesso não fornecido'
    });
  }

  jwt.verify(token, JWT_SECRET, (err: any, user: any) => {
    if (err) {
      return res.status(403).json({
        success: false,
        message: 'Token inválido ou expirado'
      });
    }

    (req as any).user = user;
    next();
  });
};

/**
 * Middleware de autenticação opcional
 */
export const optionalAuth = (req: Request, res: Response, next: NextFunction) => {
  const authHeader = req.headers['authorization'];
  const token = authHeader && authHeader.split(' ')[1];

  if (token) {
    jwt.verify(token, JWT_SECRET, (err: any, user: any) => {
      if (!err) {
        (req as any).user = user;
      }
      next();
    });
  } else {
    next();
  }
};

/**
 * Middleware para verificar se é admin
 */
export const requireAdmin = (req: Request, res: Response, next: NextFunction) => {
  const user = (req as any).user;

  if (!user) {
    return res.status(401).json({
      success: false,
      message: 'Usuário não autenticado'
    });
  }

  if (user.profile !== 'ADMIN') {
    return res.status(403).json({
      success: false,
      message: 'Acesso negado. Apenas administradores.'
    });
  }

  next();
};

/**
 * Middleware para verificar propriedade ou admin
 */
export const requireOwnershipOrAdmin = (req: Request, res: Response, next: NextFunction) => {
  const user = (req as any).user;
  const resourceUserId = req.params.userId || req.body.userId;

  if (!user) {
    return res.status(401).json({
      success: false,
      message: 'Usuário não autenticado'
    });
  }

  if (user.profile === 'ADMIN' || user.id === resourceUserId) {
    next();
  } else {
    return res.status(403).json({
      success: false,
      message: 'Acesso negado. Você não tem permissão para acessar este recurso.'
    });
  }
};


import express from 'express';

// Configurações
import { configureMiddlewares, configureErrorHandling, startServer } from './config/server';
import { connectDatabase, disconnectDatabase, runMigrations } from './config/database';

// Rotas
import apiRouter from './routes';

// Criar aplicação Express
const app = express();

/**
 * Configurar aplicação
 */
async function configureApp(): Promise<void> {
  // Conectar ao banco de dados
  await connectDatabase();
  
  // Executar migrações (comentado temporariamente)
  // await runMigrations();
  
  // Configurar middlewares
  configureMiddlewares(app);
  
  // Montar rotas da API
  app.use('/api', apiRouter);
  
  // Configurar tratamento de erros
  configureErrorHandling(app);
}

/**
 * Inicializar servidor
 */
async function initializeServer(): Promise<void> {
  try {
    await configureApp();
    startServer(app);
    
    // Graceful shutdown
    process.on('SIGTERM', async () => {
      console.log('🛑 Recebido SIGTERM, encerrando servidor...');
      await disconnectDatabase();
      process.exit(0);
    });
    
    process.on('SIGINT', async () => {
      console.log('🛑 Recebido SIGINT, encerrando servidor...');
      await disconnectDatabase();
      process.exit(0);
    });
    
  } catch (error) {
    console.error('❌ Erro ao inicializar servidor:', error);
    process.exit(1);
  }
}

// Inicializar se executado diretamente
if (require.main === module) {
  initializeServer();
}

export default app;
